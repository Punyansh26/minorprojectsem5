"""Corpus quality audit: find documents that must not be indexed as-is.

The audit reads the processed Markdown corpus (``data/processed_knowledge_base``) and reports
defects that silently destroy retrieval or answer correctness:

``thin``              almost no body text (heading-only pages, failed extractions)
``garbled_devanagari`` dropped conjuncts / orphaned matras (typical PDF text-layer damage)
``flattened_table``   runs of label+number lines that were a table before extraction
``ocr_number_noise``  numbers such as ``1, 81, 000. 000`` that cannot be trusted as written
``missing_pages``     a PDF-derived document without page anchors (no citable page)
``synthesized``       markers that text was written by a model instead of read from the source

The audit never edits a document.  It only reports; ``kbb_cli.py audit`` writes the JSON report
that drives re-extraction (see ``docs`` task list) and the later quality gate.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .store import read_json, write_json

THIN_WORDS = 80                    # body words below which a document is flagged
FLATTENED_RUN = 4                  # consecutive "label + number" lines that look like a table
GARBLE_RATIO = 0.06                # share of suspicious Devanagari tokens that flags a document
MIN_DEVANAGARI_TOKENS = 12         # below this the ratio is meaningless

_FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
_PAGE = re.compile(r"<!--\s*page:\s*(\d+)\s*-->")
_HEADING = re.compile(r"^#{1,6}\s")
_DEV_TOKEN = re.compile(r"[\u0900-\u097f]+")
_COMBINING_START = re.compile(r"^[\u093e-\u094d\u0900-\u0903\u0962\u0963]")
_MONEY_OR_NUMBER = re.compile(r"(?:₹|Rs\.?|INR)\s*[\d,. ]+\d|\b\d[\d, ]*\d\b|\b\d+\.\d+\b")
_NUMBER_NOISE = re.compile(r"\d\s*,\s+\d|\d\.\s+\d{3}\b")
_SYNTH = re.compile(r"(?i)\b(synthesi[sz]ed (?:from|by|using)|generated by (?:an? )?(?:llm|ai|model)|summary of the slide)\b")


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Separate the flat ``key: value`` YAML frontmatter from the body."""
    match = _FRONT.match(text)
    if not match:
        return {}, text
    meta = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip().strip('"')
    return meta, text[match.end():]


def body_words(body: str) -> int:
    """Words that carry content: headings, page anchors and table rules are excluded."""
    count = 0
    for line in body.splitlines():
        stripped = line.strip()
        if not stripped or _HEADING.match(stripped) or _PAGE.fullmatch(stripped):
            continue
        if re.fullmatch(r"[|\s:-]+", stripped):
            continue
        count += len(stripped.split())
    return count


def garble_ratio(text: str) -> tuple[float, int]:
    """Share of Devanagari tokens that look damaged, and the number of Devanagari tokens.

    Suspicious tokens: starting with a dependent vowel sign/virama (a conjunct was dropped),
    ending in a virama, or single consonant fragments adjacent to a double space gap.
    """
    tokens = _DEV_TOKEN.findall(text)
    if not tokens:
        return 0.0, 0
    bad = sum(1 for t in tokens if _COMBINING_START.match(t) or t.endswith("\u094d"))
    # A dropped glyph leaves two spaces inside an otherwise Devanagari phrase.
    bad += len(re.findall(r"[\u0900-\u097f] {2,}[\u0900-\u097f]", text))
    return bad / len(tokens), len(tokens)


def flattened_table_runs(body: str) -> list[tuple[int, int]]:
    """(start_line, length) of consecutive short label+number lines that are not in a table."""
    runs, start, length = [], 0, 0
    for i, line in enumerate(body.splitlines()):
        s = line.strip()
        prose_commas = len(re.findall(r"(?<!\d),|,(?!\s*\d)", s))     # commas that are not inside numbers
        is_row = (bool(s) and "|" not in s and len(s) <= 75 and prose_commas <= 1 and not _HEADING.match(s)
                  and len(_MONEY_OR_NUMBER.findall(s)) >= 1 and re.search(r"[A-Za-z\u0900-\u097f]{3}", s) is not None
                  and not re.search(r"https?://|\b(?:19|20)\d{2}\b.*\b(?:19|20)\d{2}\b", s)
                  and not re.search(r"[.;:]\s*$", s.rstrip(". ")) )
        if is_row:
            if length == 0:
                start = i
            length += 1
        else:
            if length >= FLATTENED_RUN:
                runs.append((start, length))
            length = 0
    if length >= FLATTENED_RUN:
        runs.append((start, length))
    return runs


def audit_text(text: str, *, name: str = "") -> dict[str, Any]:
    """Audit one Markdown document and return its issues (empty list = no known defect)."""
    meta, body = split_frontmatter(text)
    issues: list[dict[str, Any]] = []
    words = body_words(body)
    if words < THIN_WORDS:
        issues.append({"code": "thin", "severity": "high", "detail": f"{words} body words"})
    ratio, dev_tokens = garble_ratio(body)
    if dev_tokens >= MIN_DEVANAGARI_TOKENS and ratio >= GARBLE_RATIO:
        issues.append({"code": "garbled_devanagari", "severity": "high",
                       "detail": f"{ratio:.1%} suspicious of {dev_tokens} Devanagari tokens"})
    has_table = any(re.match(r"^\s*\|.*\|\s*$", ln) for ln in body.splitlines())
    runs = flattened_table_runs(body)
    if runs and not has_table:
        issues.append({"code": "flattened_table", "severity": "high",
                       "detail": f"{len(runs)} run(s), longest {max(n for _, n in runs)} lines"})
    elif runs:
        issues.append({"code": "flattened_table", "severity": "medium",
                       "detail": f"{len(runs)} run(s) outside real tables"})
    noise = _NUMBER_NOISE.findall(body)
    if noise:
        issues.append({"code": "ocr_number_noise", "severity": "medium", "detail": f"{len(noise)} suspicious numbers"})
    source = meta.get("source_file", name)
    if source.lower().endswith(".pdf") and not _PAGE.search(body):
        issues.append({"code": "missing_pages", "severity": "medium", "detail": "PDF source without page anchors"})
    if _SYNTH.search(text):
        issues.append({"code": "synthesized", "severity": "high", "detail": "text claims to be generated/synthesized"})
    return {"words": words, "issues": issues, "meta": meta}


def audit_corpus(processed_dir: Path, out_path: Path | None = None) -> dict[str, Any]:
    """Audit every Markdown file under ``processed_dir`` using its manifest when present."""
    documents = []
    for path in sorted(processed_dir.rglob("*.md")):
        if path.name == "SUMMARY.md":
            continue
        result = audit_text(path.read_text(encoding="utf-8", errors="replace"), name=path.name)
        meta = result["meta"]
        documents.append({
            "doc_id": meta.get("doc_id", path.stem),
            "path": str(path.relative_to(processed_dir)),
            "category": meta.get("category", path.parent.name),
            "source_file": meta.get("source_file", ""),
            "words": result["words"],
            "issues": result["issues"],
        })
    flagged = [d for d in documents if any(i["severity"] == "high" for i in d["issues"])]
    counts: dict[str, int] = {}
    for doc in documents:
        for issue in doc["issues"]:
            counts[issue["code"]] = counts.get(issue["code"], 0) + 1
    report = {"documents": len(documents), "flagged_high": len(flagged),
              "flagged_any": sum(bool(d["issues"]) for d in documents), "issue_counts": counts,
              "needs_reextraction": [d["doc_id"] for d in flagged], "details": documents}
    if out_path:
        write_json(out_path, report)
    return report


def baseline_from_legacy(legacy_state: Path, cases_path: Path, out_path: Path, *, search) -> dict[str, Any]:
    """Record what the legacy engine returns for every reviewed case (frozen comparison point).

    ``search`` is a callable ``question -> list[chunk]`` supplied by the caller so this module
    never imports the legacy package.  Each chunk needs ``source_file``, ``page_number``,
    ``block_id`` and ``text``.
    """
    cases = read_json(cases_path, [])
    rows = []
    for case in cases:
        hits = search(case["question"])
        text = "\n".join(h.text for h in hits).casefold()
        terms = case.get("required_terms", [])
        rows.append({
            "id": case["id"], "question": case["question"], "expected": case["expected"], "topic": case.get("topic"),
            "language": case.get("language"), "required_terms": terms,
            "terms_found": all(t.casefold() in text for t in terms) if terms else None,
            "returned_nothing": not hits,
            "sources": [{"source_file": h.source_file, "page": h.page_number, "block_id": h.block_id} for h in hits],
        })
    answerable = [r for r in rows if r["expected"] == "answerable"]
    summary = {"cases": len(rows), "answerable": len(answerable),
               "answerable_terms_found": sum(bool(r["terms_found"]) for r in answerable), "rows": rows}
    write_json(out_path, summary)
    return summary
