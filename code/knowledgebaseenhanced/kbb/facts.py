"""Typed, evidence-bound facts (replaces the hand-written fact lists and regex extraction).

Every record points at one evidence parent and carries the *verbatim quote* it was read from.  A record is
rejected unless

1. the evidence parent exists, is not ``needs_review``/``rejected`` and has the same source hash,
2. the quote occurs in the evidence text (whitespace, pipes and number grouping ignored), and
3. every number or date the record asserts occurs inside that quote.

Critical kinds (fee, date, cutoff, scholarship, finance) are additionally *gated*: they are served only after a
recorded review decision (``review/record_reviews.json``) or a migration marker proving prior validation.
Nothing here is generated by a model, and no total is computed - only printed values are recorded.
"""
from __future__ import annotations

import json
import re
import sqlite3
from pathlib import Path
from typing import Any, Iterable

from .textnorm import number_tokens, sha256

KINDS = {"fee", "seat", "date", "faculty", "placement", "cutoff", "scholarship", "finance"}
CRITICAL_KINDS = {"fee", "date", "cutoff", "scholarship", "finance"}
SERVABLE_EVIDENCE = {"approved", "extracted", "machine_verified"}
FILTER_FIELDS = ("year", "authority", "round", "programme", "quota", "seat_category", "gender_pool", "rank_basis")
RANK_FIELDS = ("year", "authority", "round", "programme", "quota", "seat_category", "gender_pool", "rank_basis",
               "opening_rank", "closing_rank")
MONTH = r"(?:January|February|March|April|May|June|July|August|September|October|November|December)"
SCHEMA = """CREATE TABLE records (id TEXT PRIMARY KEY, kind TEXT NOT NULL, year INTEGER, authority TEXT, round TEXT,
 programme TEXT, quota TEXT, seat_category TEXT, gender_pool TEXT, rank_basis TEXT,
 evidence_block_id TEXT NOT NULL, review_status TEXT NOT NULL, label TEXT, payload TEXT NOT NULL)"""


class FactError(ValueError):
    """A record that is not supported by its evidence."""


def squash(text: str) -> str:
    """Comparison form: no pipes, collapsed whitespace, grouping spaces inside numbers removed."""
    text = (text or "").replace("|", " ").replace("`", "")
    text = re.sub(r"(?<=\d)\s*,\s*(?=\d)", ",", text)
    return " ".join(text.split()).casefold()


def quote_in(quote: str, text: str) -> bool:
    return bool(quote.strip()) and squash(quote) in squash(text)


def record_id(rec: dict) -> str:
    keys = ("kind", "evidence_block_id", "quote", "name", "label", "event", "metric", "programme", "quota",
            "seat_category", "year", "round", "gender_pool", "authority", "rank_basis")
    return sha256(json.dumps({k: rec.get(k) for k in keys}, sort_keys=True, ensure_ascii=False))[:24]


def _field(evidence: Any, name: str):
    """Evidence may be a legacy-style dict or a ``Parent``."""
    if isinstance(evidence, dict):
        return {"status": evidence.get("verification_status"), "text": evidence.get("text", ""),
                "sha": evidence.get("source_sha256")}[name]
    return {"status": evidence.status, "text": evidence.text, "sha": evidence.meta.get("source_sha256")}[name]


def validate_record(rec: dict, parents: dict[str, Any]) -> None:
    """Raise ``FactError`` unless the record is fully supported by its evidence parent."""
    kind = rec.get("kind")
    if kind not in KINDS:
        raise FactError(f"unknown kind {kind!r}")
    evidence = parents.get(rec.get("evidence_block_id"))
    if evidence is None:
        raise FactError("evidence parent missing")
    text = _field(evidence, "text")
    if _field(evidence, "status") not in SERVABLE_EVIDENCE:
        raise FactError(f"evidence status {_field(evidence, 'status')} cannot support a fact")
    if rec.get("source_sha256") != _field(evidence, "sha"):
        raise FactError("source hash differs from evidence")
    if kind == "cutoff":
        if any(rec.get(k) in (None, "") for k in RANK_FIELDS):
            raise FactError("cutoff lacks an explicit dimension")
        for name in ("opening_rank", "closing_rank"):
            if not re.fullmatch(r"\d+(?:\.\d+)?P?", str(rec[name])):
                raise FactError("invalid rank value")
            if str(rec[name]) not in text:
                raise FactError("rank absent from approved source row")
        if float(str(rec["opening_rank"]).rstrip("P")) > float(str(rec["closing_rank"]).rstrip("P")):
            raise FactError("opening rank exceeds closing rank")
        return
    if kind in {"scholarship", "finance"} and not rec.get("quote"):
        if not rec.get("name") or not rec.get("conditions") or rec.get("institution_applicability") not in {"verified", "unknown", "not_applicable"}:
            raise FactError("financial support must keep its conditions and applicability")
        linked = [text]
        for key in rec.get("related_evidence_block_ids", []):
            other = parents.get(key)
            if other is None or _field(other, "status") not in SERVABLE_EVIDENCE or _field(other, "sha") != rec["source_sha256"]:
                raise FactError("financial conditions need servable evidence from the same source")
            linked.append(_field(other, "text"))
        joined = "\n".join(linked)
        for key in ("conditions", "benefit"):
            if rec.get(key) and not quote_in(rec[key], joined):
                raise FactError(f"{key} is not a source extract")
        return
    quote = rec.get("quote", "")
    if not quote_in(quote, text):
        raise FactError("quote is not in the evidence text")
    asserted = {"fee": ["amount"], "seat": ["seats"], "placement": [], "date": [], "faculty": []}[kind]
    quote_numbers = set(number_tokens(quote))
    for name in asserted:
        if rec.get(name) is None or str(int(rec[name])) not in quote_numbers:
            raise FactError(f"{name} is not printed in the quote")
    if kind == "date" and not quote_in(rec.get("date_text", ""), quote):
        raise FactError("date text is not in the quote")
    if kind == "faculty" and not quote_in(rec.get("name", ""), quote):
        raise FactError("faculty name is not in the quote")
    if kind == "placement" and not quote_in(str(rec.get("value", "")), quote):
        raise FactError("placement value is not in the quote")


# ---------------------------------------------------------------- builders from verified evidence
def _rows(text: str) -> list[list[str]]:
    rows = []
    for line in text.splitlines():
        if "|" in line and not re.fullmatch(r"[|\s:-]+", line):
            rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows


def fee_records(parent) -> list[dict]:
    """One record per ``label | amount`` row of a fee table (header must contain 'fee' and 'amount')."""
    rows = _rows(parent.text)
    header = " ".join(rows[0]).casefold() if rows else ""
    if parent.kind != "table" or "fee" not in header or "amount" not in header:
        return []
    out = []
    for row in rows[1:]:
        if len(row) < 2 or not re.search(r"\d", row[-1]) or ("₹" not in row[-1] and "rs" not in row[-1].casefold()):
            continue
        tokens = number_tokens(row[-1])
        if len(tokens) != 1:
            continue
        name = next((c for c in row[:-1] if re.search(r"[A-Za-z\u0900-\u097f]{3}", c)), "")
        if not name:
            continue
        name = re.sub(r"\s+", " ", name).strip()
        out.append({"kind": "fee", "name": name, "amount": int(float(tokens[0])), "currency": "INR",
                    "quote": " | ".join(row), "label": name, "context": parent.meta.get("title", "")})
    return out


def date_records(parent) -> list[dict]:
    """Rows whose last cell is a printed date (calendar, holidays, admission schedule)."""
    out = []
    for row in _rows(parent.text):
        # A schedule row is "event | date": publication lists and long citations are not schedules.
        if not 2 <= len(row) <= 4 or len(row[-1]) > 60 or len(row[0]) > 110:
            continue
        label = next((c for c in row[:-1] if re.search(r"[A-Za-z\u0900-\u097f]{3}", c)), "")
        if label and re.search(MONTH, row[-1], re.I) and re.search(r"\d", row[-1]):
            label = re.sub(r"\s+", " ", label).strip()
            out.append({"kind": "date", "event": label, "date_text": row[-1], "quote": " | ".join(row),
                        "label": label, "context": parent.meta.get("title", "")})
    return out


def faculty_records(parent) -> list[dict]:
    rows = _rows(parent.text)
    if not rows or "faculty name" not in " ".join(rows[0]).casefold():
        return []
    out = []
    for row in rows[1:]:
        if len(row) >= 5:
            name = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", row[0])
            out.append({"kind": "faculty", "name": name, "designation": row[1], "department": row[2],
                        "email": row[4].strip("` ").replace("[at]", "@"), "quote": " | ".join(row), "label": name,
                        "context": parent.meta.get("title", "")})
    return out


def build_records(parents: dict[str, Any], curated: Iterable[dict]) -> tuple[list[dict], list[dict]]:
    """Auto-derived + curated records.  Returns (valid, rejected-with-reason); nothing invalid is stored."""
    candidates: list[dict] = []
    for parent in parents.values():
        if parent.status not in SERVABLE_EVIDENCE:
            continue
        category = parent.meta.get("category", "")
        derived = fee_records(parent) + (date_records(parent) if category != "faculty" else []) + faculty_records(parent)
        for rec in derived:
            candidates.append({**rec, "evidence_block_id": parent.id, "source_sha256": parent.meta.get("source_sha256")})
    for spec in curated:
        base = Path(spec["source"]).name.split("*")[0]
        match = next((p for p in parents.values()
                      if Path(p.meta.get("source_file", "")).name.startswith(base)
                      and (spec.get("page") is None or p.page_start <= spec["page"] <= p.page_end)
                      and quote_in(spec["quote"], p.text) and p.status in SERVABLE_EVIDENCE), None)
        rec = {k: v for k, v in spec.items() if k not in {"source", "page"}}
        rec.update(evidence_block_id=match.id if match else "",
                   source_sha256=match.meta.get("source_sha256") if match else None)
        candidates.append(rec)
    valid, rejected, seen = [], [], set()
    for rec in candidates:
        try:
            validate_record(rec, parents)
        except FactError as error:
            rejected.append({"record": {k: rec.get(k) for k in ("kind", "name", "event", "metric", "quote")}, "reason": str(error)})
            continue
        rec["id"] = rec.get("id") or record_id(rec)
        if rec["id"] not in seen:
            seen.add(rec["id"])
            valid.append(rec)
    return valid, rejected


# ---------------------------------------------------------------- storage and lookup
def create_database(path: Path, records: list[dict], parents: dict[str, Any], decisions: dict[str, dict]) -> list[dict]:
    """Write validated records.  ``decisions`` maps record id -> {"decision": approved|rejected, ...}."""
    if path.exists():
        path.unlink()
    out = []
    with sqlite3.connect(path) as conn:
        conn.execute(SCHEMA)
        conn.execute("CREATE INDEX dims ON records(kind,year,authority,programme,quota,seat_category,round)")
        for rec in records:
            validate_record(rec, parents)
            decision = (decisions.get(rec["id"]) or {}).get("decision")
            if rec["kind"] in CRITICAL_KINDS:
                status = decision or ("approved" if rec.get("migrated_validated") else "pending")
            else:
                status = decision or "approved"
            rec = {**rec, "review_status": status}
            columns = ("id", "kind", *FILTER_FIELDS, "evidence_block_id", "review_status", "label")
            conn.execute(f"INSERT INTO records ({','.join(columns)},payload) VALUES ({','.join('?' * (len(columns) + 1))})",
                         [rec.get(k) for k in columns] + [json.dumps(rec, ensure_ascii=False)])
            out.append(rec)
    return out


def _connect(path: Path):
    return sqlite3.connect(f"file:{path.resolve()}?mode=ro", uri=True)


def lookup_cutoffs(path: Path, filters: dict, limit: int = 12) -> list[dict]:
    """Exact parameterised cutoff lookup.  No match returns [] - never a nearby number."""
    if not path.exists():
        return []
    unknown = set(filters) - set(FILTER_FIELDS)
    if unknown:
        raise ValueError(f"unsupported cutoff filter {sorted(unknown)}")
    clauses, args = ["kind = 'cutoff'", "review_status = 'approved'"], []
    for key, value in filters.items():
        clauses.append(f"{key} = ?")
        args.append(value)
    with _connect(path) as conn:
        rows = conn.execute("SELECT payload FROM records WHERE " + " AND ".join(clauses) +
                            " ORDER BY year DESC, CAST(round AS INTEGER) DESC, programme, seat_category, gender_pool LIMIT ?",
                            [*args, limit]).fetchall()
    return [json.loads(r[0]) for r in rows]


KIND_WORDS = {
    "fee": r"\b(fee|fees|tuition|charges?|cost|deposit|mess advance|payable)\b|शुल्क|फीस",
    "seat": r"\b(seats?|intake|quota)\b|सीट",
    "date": r"\b(when|date|dates|schedule|holiday|exam|examination|orientation|convocation|results?|classes)\b|कब|तारीख|तिथि",
    "faculty": r"\b(professor|faculty|dr\.?|email|e-mail|department|designation|dean|hod)\b|प्राध्यापक|प्रोफेसर",
    "placement": r"\b(placements?|ctc|lpa|package|recruiters?|companies|offers)\b|प्लेसमेंट",
}
STOP = {"the", "and", "for", "what", "how", "much", "does", "are", "iiit", "naya", "raipur", "kitni", "kitna",
        "hai", "ki", "ka", "ke", "kya", "when", "who", "which", "from", "with", "this", "that"}


def _terms(text: str) -> set[str]:
    return {t for t in re.findall(r"[a-z0-9]+", squash(text)) if len(t) > 2 and t not in STOP}


def match_records(path: Path, question: str, limit: int = 6) -> list[dict]:
    """Approved records whose own words overlap the question and whose kind the question asks about."""
    if not path.exists():
        return []
    wanted = [k for k, pat in KIND_WORDS.items() if re.search(pat, question, re.I)]
    if not wanted:
        return []
    q_terms = _terms(question)
    with _connect(path) as conn:
        rows = conn.execute(f"SELECT payload FROM records WHERE kind IN ({','.join('?' * len(wanted))}) "
                            "AND review_status = 'approved'", wanted).fetchall()
    scored = []
    for (payload,) in rows:
        rec = json.loads(payload)
        label_terms = _terms(" ".join(str(rec.get(k, "")) for k in
                                      ("label", "name", "event", "metric", "programme", "quota", "seat_category",
                                       "designation", "department", "context")))
        overlap = len(q_terms & label_terms)
        if overlap >= 1:
            scored.append((overlap, rec))
    scored.sort(key=lambda x: (-x[0], x[1]["id"]))
    return [r for _, r in scored[:limit]]


def stats(path: Path) -> dict[str, dict[str, int]]:
    out: dict[str, dict[str, int]] = {}
    with _connect(path) as conn:
        for kind, status, n in conn.execute("SELECT kind, review_status, COUNT(*) FROM records GROUP BY kind, review_status"):
            out.setdefault(kind, {})[status] = n
    return out
